import { chromium } from "@playwright/test";
import { readFileSync } from "node:fs";
const B = process.env.BASE_URL;
const pwd = readFileSync(".env.local", "utf8").match(/^ADMIN_PASSWORD=(.*)$/m)[1];
const b = await chromium.launch({ channel: "msedge" });
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
const net = [];
p.on("response", (r) => r.request().method() === "POST" && net.push(`${r.status()} ${r.url().replace(B, "")}`));
await p.goto(`${B}/admin/login`); await p.fill("#password", pwd); await p.click("button[type=submit]"); await p.waitForURL(`${B}/admin`);
await p.goto(`${B}/admin/newsletter/nova`);
await p.fill('input[name="subject"]', "TESTE PROBE"); await p.fill('textarea[name="body"]', "Teste.");
await p.click("text=Criar rascunho"); await p.waitForURL(/\/admin\/newsletter\/\d+/);
await p.fill('input[name="test_to"]', "delivered@resend.dev");
await p.getByRole("button", { name: "Enviar teste" }).click();
await p.waitForTimeout(12000);
console.log("POSTs:", net);
console.log("status:", await p.locator('[role=status],[role=alert]').allTextContents());
await p.click("text=Excluir rascunho"); await p.waitForURL(`${B}/admin/newsletter`);
await b.close();
